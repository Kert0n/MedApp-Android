package com.kert0n.medapp.queue.medkit

import com.kert0n.medapp.domain.medkit.MedKit
import com.kert0n.medapp.domain.pack.Package
import com.kert0n.medapp.network.pack.PackageSnapshot
import java.time.Instant
import kotlin.uuid.Uuid

/**
 * Что публикации нужно от хранилища — и только это (PLAN E5). Публикация — сетевое действие
 * между двумя транзакциями: прочитать аптечку с содержимым, записать переключение вместе с
 * первыми подтверждёнными остатками. Реализация живёт в хранении; сеть про порт не знает.
 */
interface PublicationStorage {

    suspend fun medKit(id: Uuid): MedKit?

    /** Живые пачки аптечки — то, что уедет на сервер. */
    suspend fun contentsOf(medKitId: Uuid): List<Package>

    /**
     * Момент передачи ответственности серверу: аптечка становится опубликованной, а ответы на
     * создание её пачек — первым подтверждённым остатком и версиями — одной транзакцией.
     *
     * Принимает **номер** аптечки, а не прочитанный до сети экземпляр: между чтением и этой
     * записью человек продолжал жить, и переход применяется к тому, что лежит в базе. Иначе
     * переименование, сделанное пока шла сеть, затиралось бы старым именем, а удалённая аптечка
     * воскресала бы вставкой (PLAN E4, F5).
     *
     * Пачки читает и ответ пишет один владелец: изменившаяся или появившаяся пачка значит, что
     * старый серверный снимок лёг бы поверх нового местного расхода. Тогда не пишется ничего —
     * публиковать заново; повтор идемпотентен по идентификаторам (E5).
     */
    suspend fun publish(medKitId: Uuid, snapshots: List<PackageSnapshot>, at: Instant): Switch

    /** Чем кончилась запись переключения — всё, что различает поведение сценария. */
    enum class Switch {

        /** Ответственность у сервера, первые подтверждённые остатки записаны. */
        PUBLISHED,

        /** Аптечку убрали, пока шла публикация: переключать нечего. */
        MED_KIT_GONE,

        /** Она уже общая — повторная публикация ничего не меняет. */
        ALREADY_PUBLISHED,

        /** Пачки менялись между чтением и записью: переключения нет, публиковать заново. */
        CHANGED_MEANWHILE
    }
}
