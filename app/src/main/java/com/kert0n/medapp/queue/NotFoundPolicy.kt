package com.kert0n.medapp.queue

/**
 * Что значит 404 для команды: у каждой — своё, потому что 404 отвечают разные ресурсы (PLAN
 * B4, E3). Пачки или аптечки нет — доступа нет; своей брони нет, где её правят или снимают, —
 * желаемое состояние готовится заново либо уже наступило; удаляемой пачки нет — она уже удалена.
 */
enum class NotFoundPolicy { ACCESS_LOST, REPREPARE, APPLIED }
