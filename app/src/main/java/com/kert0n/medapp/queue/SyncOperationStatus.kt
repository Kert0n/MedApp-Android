package com.kert0n.medapp.queue

/**
 * Состояние операции очереди — ровно то, с чем работник и зависимые операции поступают
 * по-разному (PLAN E2). Слой данных: домен о статусах отправки не спрашивает — ему приходит
 * уже свёрнутое число. Неопределённости среди состояний нет: повтор с неизвестным исходом идёт
 * тем же запросом, а «устарело» — не состояние, а известный исход, после которого запрос
 * готовится заново и операция снова ждёт.
 */
enum class SyncOperationStatus {

    /** Ожидает отправки или повтора. Собранный запрос менять нельзя; сброшенный — собирается заново. */
    PENDING,

    /** Запрос выполняется. После смерти процесса отправляется снова тем же запросом. */
    SENDING,

    /** Сервер сделал, что просили; истина прочитана снимком. Зависимые операции идут. */
    APPLIED,

    /**
     * Сервер делать не будет: неверный ввод, расход больше остатка, чужая правка перекрыла
     * описание. Причина названа в `lastError`, истина прочитана снимком; зависимые отказываются
     * следом — им нужен был эффект, которого не будет.
     */
    REFUSED,

    /** Доступ к аптечке или упаковке утрачен, отправлять больше некуда; зависимые теряются следом. */
    ACCESS_LOST;

    /** Закрытая операция: работник её не трогает, свёртка остатка не считает. */
    val isClosed: Boolean get() = this == APPLIED || this == REFUSED || this == ACCESS_LOST
}
