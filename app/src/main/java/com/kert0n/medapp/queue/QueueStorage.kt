package com.kert0n.medapp.queue

import java.time.Instant
import kotlin.uuid.Uuid

/**
 * Что очереди нужно от хранилища — и только это. Транзакция принадлежит хранилищу: заморозить
 * запрос и перевести операцию в отправку, закрыть операцию и применить ответ сервера — каждое
 * ложится одной транзакцией там, где лежат таблицы (PLAN F5). Репозитории про очередь не знают;
 * реализация живёт в хранении.
 */
interface QueueStorage {

    /**
     * Готовые к отправке, по порядку номера: ожидающие и те, что отправлялись в момент смерти
     * процесса, у которых все зависимости закрыты. Нечитаемые строки — тоже здесь, с причиной:
     * работник их пропускает, а промах словаря дочитывает.
     */
    suspend fun ready(): List<StoredSyncOperation>

    /**
     * Берёт операцию в отправку: замораживает запрос, если он ещё не собран, — с теми
     * предусловиями, что у пачки сейчас, — и переводит в `SENDING`. Собранный запрос не
     * пересобирается никогда (PLAN E2). `null` — операции нет или она уже закрыта.
     */
    suspend fun take(id: Uuid, at: Instant): SyncOperation?

    /** Отпускает операцию с исходом; что исход значит для строк, решает хранилище. */
    suspend fun settle(id: Uuid, outcome: Delivery, at: Instant)

    /** Одна транзакция на изменение и его команду: порознь их не бывает (PLAN F5). */
    suspend fun <T> transaction(block: suspend () -> T): T

    /** Ставит команду; номер выдаёт хранилище. Только внутри [transaction] с её причиной. */
    suspend fun enqueue(queued: QueuedCommand, at: Instant): SyncOperation
}
