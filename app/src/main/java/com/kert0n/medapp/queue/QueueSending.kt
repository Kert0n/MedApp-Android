package com.kert0n.medapp.queue

/**
 * Кому сказать, что серверу есть что узнать. Просьба уходит **после коммита** и не ждёт ответа:
 * изменение уже записано, его исход от сети не зависит, и действие человека сетевого круга не
 * ждёт (PLAN E4, F5).
 *
 * Порт, а не прямой вызов работника: кто ставит команды, не должен знать, чем и когда они
 * отправляются, — а проверке записи сеть не нужна вовсе.
 */
fun interface QueueSending {

    fun soon()

    companion object {

        /** Никуда не спешит: для проверок записи, где отправлять нечем и незачем. */
        val none: QueueSending = QueueSending {}
    }
}
