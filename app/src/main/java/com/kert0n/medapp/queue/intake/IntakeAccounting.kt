package com.kert0n.medapp.queue.intake

/**
 * Где находится расход, записанный приёмом: в локальном остатке, в очереди или на сервере.
 *
 * Слой данных, а не домен. В локальной аптечке исходящих операций нет вовсе (PLAN E1), и всё это
 * различение существует только из-за сервера: ни одно бизнес-правило о приёме — переходы, доза,
 * обеспечение — его не читает.
 */
enum class IntakeAccounting {

    /** Расхода нет: плановый, пропущенный, неотвеченный или отменённый пункт. */
    NOT_APPLICABLE,

    /** Локальный остаток и факт записаны одной транзакцией (PLAN F5). */
    LOCAL_APPLIED,

    /** Факт есть, серверная команда ещё не подтверждена. */
    PENDING,

    /** Сервер списал: серверный остаток факт включает — либо пачка списана им до нуля и уничтожена. */
    REMOTE_APPLIED,

    /**
     * Серверный остаток факт **не включает**, и это известно: расход больше остатка, единица
     * пачки сменилась, либо пачки для нас не стало до применения. Факт остаётся; экран показывает
     * расхождение и путь к пересчёту (PLAN E3).
     */
    REMOTE_REFUSED
}
