package com.kert0n.medapp.queue

/**
 * Одна транзакция — и всё. Узкий порт для тех, кому нужно «изменение и его команда ложатся
 * вместе, или не ложится ничего» (PLAN F5): сценарий человека и служба очереди.
 *
 * Отдельно от [QueueStorage], потому что тому, кто пишет приём, нечего делать с заморозкой
 * запроса, взятием в отправку и установлением исхода: это порт работника очереди. Реализация —
 * `RoomTransactions` в хранении; здесь только обещание.
 */
interface Transactions {

    suspend fun <T> run(block: suspend () -> T): T
}
