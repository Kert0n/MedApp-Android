package com.kert0n.medapp.queue

/**
 * Что значит 409 для этой команды. О версии он больше не говорит — устаревшую версию сервер
 * отвергает 412, а не названную 428 (PLAN B4, E3). Остаётся три случая, и поведение у них разное.
 */
enum class ConflictPolicy {

    /** Объект с нашим номером уже есть: читаем — наш, значит уже применено. */
    EXISTS,

    /** Бронь уже заявлена: по свежему `mine` та же команда становится правкой. */
    REPREPARE,

    /**
     * Тот же номер с другим телом. Повторять нечем: журнал сервера ответит так же всегда, а тело
     * запроса при переподготовке не меняется — значит, это дефект клиента, а не состояние сервера.
     */
    REFUSE
}
