package com.kert0n.medapp.queue

/**
 * Почему сервер не сделал, что просили, — значение, а не текст: экран берёт слова из
 * `R.string.*`, а `lastError` остаётся для журнала (PLAN H1).
 */
enum class RefusalReason {

    /** Неверный ввод: 400 по полям или условиям, 428 без версии — дефект, а не состояние. */
    INVALID,

    /** Расход больше серверного остатка: 400 у `sync`. Факт остаётся, остаток его не включает. */
    INSUFFICIENT,

    /** Единицу пачки сменили на сервере: дозу в прежней единице из неё не списать. */
    UNIT_CHANGED,

    /** Чужая правка перекрыла намерение: описание, пересчёт, перенос, удаление устарели. */
    STALE,

    /** Отказана или потеряна операция, эффект которой был нужен этой. */
    SUPERSEDED
}
