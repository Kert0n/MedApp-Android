package com.kert0n.medapp.network.server

/**
 * Состояние операции очереди — ровно то, что различает работник (PLAN E2).
 *
 * Слой данных, и это не формальность: домен о статусах отправки не спрашивает вовсе. Ему
 * приходит уже свёрнутое число — подтверждённый остаток с незакрытыми командами поверх.
 * Неопределённости среди состояний нет: повтор безопасен замороженным предусловием, и
 * «неизвестно, применилось ли» длится до следующей связи, а не живёт статусом.
 */
enum class SyncOperationStatus {

    /** Ожидает отправки или повтора. Сохранённый запрос, если он уже собран, менять нельзя. */
    PENDING,

    /** Запрос выполняется. После смерти процесса отправляется снова тем же запросом. */
    SENDING,

    /**
     * Отправка закончена: сервер применил команду либо отверг её по предусловию. Отказ назван в
     * `lastError`, а истина по количеству в обоих случаях прочитана снимком — истина на сервере.
     */
    DONE,

    /** Доступ к аптечке или упаковке утрачен, отправлять больше некуда. */
    ACCESS_LOST
}
