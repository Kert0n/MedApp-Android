package com.kert0n.medapp.network.server

/**
 * Состояние исхода операции очереди — ровно то, что нужно проекциям (PLAN E2).
 *
 * Слой данных, и это не формальность: домен о статусах отправки не спрашивает вовсе. Ему
 * приходит уже свёрнутое число — подтверждённый остаток с незакрытыми командами поверх. Собрать
 * сетевые исходы в один содержательный вопрос — работа очереди, и делается она здесь.
 */
enum class SyncOperationStatus {

    /** Ожидает отправки. Сохранённый запрос, если он уже собран, менять нельзя. */
    PENDING,

    /** Запрос выполняется. */
    SENDING,

    /** Исход неизвестен, идёт проверочное чтение (PLAN E3). */
    VERIFYING,

    /** Применение установлено. */
    DONE,

    /**
     * Исход не установлен, и расход **не повторяется автоматически**: повтор списал бы дважды.
     * Пока это состояние держится, точное «свободно» по пачке не обещается.
     */
    NEEDS_RECOUNT,

    /** Операция учтена ручной сверкой; её прежний исход так и остаётся неизвестным. */
    RECONCILED,

    /** Неотправленное намерение вошло в более позднюю ручную сверку. */
    SUPERSEDED,

    /** Явный отказ или конфликт: ввод сохранён, решение за человеком. */
    CONFLICT,

    /** Доступ к аптечке или упаковке утрачен, отправлять больше некуда. */
    ACCESS_LOST
}
