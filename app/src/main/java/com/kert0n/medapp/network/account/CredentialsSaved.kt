package com.kert0n.medapp.network.account

/**
 * Легла ли выданная учётка на устройство. Случая два, и дальше делается разное: [SAVED] — можно
 * работать; [LOST] — сервер показал ключ единственный раз, записать его не удалось, и учётка
 * потеряна вместе с ним (PLAN G2).
 *
 * Поэтому запись не бросает: потеря выданного ключа — это исход регистрации, о котором говорят
 * человеку, а не сбой, от которого можно отмахнуться повтором.
 */
enum class CredentialsSaved { SAVED, LOST }
