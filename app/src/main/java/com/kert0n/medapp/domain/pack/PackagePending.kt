package com.kert0n.medapp.domain.pack

/**
 * Что доставка делает с коробкой прямо сейчас — ровно те случаи, которые экран показывает
 * по-разному (PLAN E1, H3).
 *
 * Это **не состояние коробки**: живая строка значит «что подтвердила полка», а решение, до которого
 * полка ещё не дошла, живёт незакрытой командой в очереди. Поэтому здесь три случая, а не колонка в
 * таблице: `Lifecycle` вернулся бы к тому, от чего отказались (PLAN D3).
 *
 * Отличается от «в показанное число вложено незакрытое изменение»: то — о числе, а это — о самой
 * коробке. Правка описания числа не трогает, но коробку помечает.
 */
enum class PackagePending {

    /** Ничего не в пути: показано то, что подтвердила полка. */
    NOTHING,

    /** Изменение записано, полка о нём ещё не знает: коробка помечена, но ею пользуются. */
    CHANGES,

    /**
     * Человек решил выбросить коробку, полка ещё не согласилась. Коробка видна, но неактивна:
     * принять из неё нельзя и источником курса её не назначают — решение уже принято, а вернуть
     * его в этой редакции нечем.
     */
    REMOVAL
}
