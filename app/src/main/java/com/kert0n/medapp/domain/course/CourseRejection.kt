package com.kert0n.medapp.domain.course

/**
 * Причины, по которым курс отказывает в действии.
 *
 * Значение перечисления, а не текст: сообщение человеку живёт в `R.string.*`, иначе домен начал
 * бы решать, на каком языке говорит приложение (PLAN H1). Различать причины обязательно —
 * «укажите форму пачки» и «эта пачка другой формы» ведут человека к разным действиям, а одно
 * «нельзя подключить» не ведёт ни к какому.
 */
enum class CourseRejection {

    /** Пачка израсходована, утилизирована или доступ к ней утрачен. */
    PACKAGE_UNUSABLE,

    /** Эта пачка уже источник курса: второй раз она в стек не встаёт. */
    ALREADY_ATTACHED,

    /**
     * У пачки не заполнена форма.
     *
     * «Форма неизвестна» и «форма неизвестна» — не одно и то же: это две пачки, про каждую из
     * которых мы ничего не знаем. Чтобы подключить пачку к курсу, форму надо сначала заполнить
     * (PLAN D5).
     */
    FORM_UNKNOWN,

    /** Форма пачки отличается от формы курса, зафиксированной первым источником. */
    FORM_MISMATCH,

    /** Единица пачки отличается от единицы курса: величины в разных единицах не считаются. */
    UNIT_MISMATCH,

    /**
     * Курс завершён или отменён: его источники — история, и она не правится.
     *
     * Случая «действие только для черновика» здесь нет: активировать назначенный курс или
     * задать ему дозу нечем — этих переходов у его типа не существует (PLAN D5).
     */
    COURSE_CLOSED,

    /** Активировать нечего: расписания нет. */
    SCHEDULE_MISSING,

    /** Активировать нечего: разовая доза не задана. */
    DOSE_MISSING,

    /** Активировать нечего: ни одного источника не подключено. */
    SOURCES_MISSING
}
