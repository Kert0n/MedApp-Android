package com.kert0n.medapp.domain.course

import java.time.Instant
import java.time.LocalDate
import java.time.LocalTime

/**
 * Один пункт расписания: назначенные человеком дата и время — и момент, когда они наступают.
 *
 * Локальные дата и время здесь **исходные**, до разрешения перехода на летнее время: тождество
 * пункта дают именно они (PLAN F4), поэтому повторная материализация окна идемпотентна, а
 * нажатие старого уведомления находит тот же пункт.
 *
 * [at] — результат разрешения, и он может совпасть у двух разных пунктов: два времени внутри
 * одного пропущенного часа сдвигаются вперёд в один и тот же момент и остаются **двумя**
 * назначенными приёмами. Уникальность по [at] здесь была бы потерей пункта.
 */
data class ScheduledOccurrence(
    val localDate: LocalDate,
    val localTime: LocalTime,
    val at: Instant
)
