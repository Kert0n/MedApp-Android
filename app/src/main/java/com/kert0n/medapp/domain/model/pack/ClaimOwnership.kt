package com.kert0n.medapp.domain.model.pack

import com.kert0n.medapp.domain.model.course.CourseBrief

/**
 * Чем объяснена **моя** бронь на пачку (`Claims.mine`).
 *
 * Вопрос содержательный, а не технический. Домену нужен смысл — бронь объяснена локальным
 * назначением, снята локально или владельца у неё нет, — а не признак «есть ожидающий запрос»:
 * ожидающая команда очереди лишь **один из источников** этого смысла, и её отсутствие ничего не
 * доказывает. Поэтому здесь три случая, а не булев флаг доставки.
 *
 * От ответа зависит одно число D4: бесхозная бронь вычитается из доступного, потому что человек
 * сначала разбирает неизвестное назначение — **её не снимают и не переназначают молча**.
 */
sealed interface ClaimOwnership {

    /** Бронь объясняется назначением: пачка выделена этому курсу. */
    data class AssignedTo(val course: CourseBrief) : ClaimOwnership

    /**
     * Снята локально, сервер об этом ещё не знает.
     *
     * Не бесхозная: назначение уже разобрано человеком, и вычитать её из доступного значило бы
     * скрыть запас, который вот-вот освободится.
     */
    data object ReleasedLocally : ClaimOwnership

    /**
     * Владельца нет: своя бронь обнаружена, а курса, который бы её объяснял, у нас не нашлось.
     *
     * Это и есть бесхозная бронь (PLAN D4). Она вычитается из доступного и показывается отдельно,
     * пока человек не разберёт назначение сам.
     */
    data object NoKnownOwner : ClaimOwnership
}
