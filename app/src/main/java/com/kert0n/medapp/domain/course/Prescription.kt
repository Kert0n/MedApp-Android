package com.kert0n.medapp.domain.course

import com.kert0n.medapp.domain.value.Quantity

/**
 * Назначение: сколько принимать за раз и по какому календарю. То, что человек себе назначил и что
 * после начала лечения **неизменно** — изменившееся лечение это отмена и новый курс (PLAN D5).
 *
 * Величина, и лежит она в двух местах сразу: у живого плана, который ею пользуется, и у записи
 * эпизода, которая переживёт план. Расхождения быть не может именно потому, что менять её нечем.
 */
data class Prescription(
    val dose: Quantity,
    val schedule: CourseSchedule
)
