package com.kert0n.medapp.domain.model.course

import com.kert0n.medapp.domain.model.value.Doses
import kotlin.uuid.Uuid

/**
 * Источник курса: пачка и сколько целых плановых доз из неё ещё выделено.
 *
 * **Величина, а не сущность.** Тождество даёт пара (курс, упаковка), а приоритет — место в
 * списке источников, поэтому отдельного `CourseSourceId` не существует и не нужен (PLAN D5).
 * Переставить источники — значит получить другой стек, а не изменить один из них.
 *
 * **Выделение в дозах, а не в таблетках.** Доза 2, в одной пачке свободна одна таблетка и в
 * другой одна: в таблетках человек выделит 1 + 1, сумма сравняется с потребностью на приём,
 * ползунки зажмутся — а покрытие ноль, потому что доза между пачками не делится. Выхода из
 * этого состояния нет. В дозах то же самое читается честно: `floor(1/2) = 0` в каждой пачке,
 * выделено ноль, не хватает одной дозы (PLAN D5).
 *
 * [allocatedDoses] — **оставшееся** выделение, а не первоначальное назначение: подтверждённая
 * доза уменьшает его на одну. Восстановить изначальное только по приёмам нельзя — человек мог
 * двигать ползунки, и история ручных перераспределений в первой версии не обещается.
 */
data class CourseSource(
    val packageId: Uuid,
    val allocatedDoses: Doses
)
