package com.kert0n.medapp.domain.intake

/**
 * Состояние приёма, выведенное из ответа: у пункта курса — из [IntakeAnswer], у внепланового
 * факта всегда [TAKEN]. Переходы: [PLANNED] → [TAKEN] / [MISSED] / [CANCELLED] и
 * [MISSED] → [TAKEN] (PLAN D6). Ответов два — принято и не принято: отказ человека и неответ в
 * жизни одно и то же, лечение от них не короче, и различить их экрану нечем.
 */
enum class IntakeStatus {

    /** Пункт плана, ответа ещё нет. */
    PLANNED,

    /** Подтверждён: есть фактическое количество, пачка и момент. */
    TAKEN,

    /**
     * Не принят — отказался или не ответил до конца дня. Расхода нет, а потребность не
     * уменьшается: доза уезжает вперёд, и подтвердить её ещё можно.
     */
    MISSED,

    /** Плановый пункт отменён вместе с курсом. История остаётся. */
    CANCELLED
}
