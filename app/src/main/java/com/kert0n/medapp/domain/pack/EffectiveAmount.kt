package com.kert0n.medapp.domain.pack

import com.kert0n.medapp.domain.value.Quantity
import kotlin.uuid.Uuid

/**
 * Что мы вправе утверждать о количестве в пачке: число — или «неизвестно, нужна сверка».
 *
 * **Оценка приходит готовой.** Какие незакрытые команды входят в неё и в каком порядке — правило
 * очереди, и живёт оно в слое данных вместе с номерами `sequence` (PLAN E1 — это часть E,
 * «Синхронизация», а не D). Домен получает результат и считает по нему бизнес-правила D4:
 * чужие брони, бесхозную бронь, свободное и доступное мне.
 *
 * **Два случая, а не число с признаком.** Пока «остаток» и «нужна сверка» лежали рядом двумя
 * полями, любой экран мог напечатать число, которого мы не знаем. Здесь у [NeedsRecount] числа
 * просто нет — есть последнее наблюдение, названное своим именем.
 *
 * Виды вложены, а не разложены по файлам: это два исхода одного вопроса, как `Mapped` и
 * `Rejected` у приведения ввода, а не самостоятельные понятия (PLAN H1).
 */
sealed interface EffectiveAmount {

    /**
     * Количество известно.
     *
     * [confirmed] — число целиком подтверждено сервером (или пачка вообще не опубликована, и
     * подтверждать его некому). `false` означает, что в него уже вложены незакрытые локальные
     * изменения: расход записан, а ответа ещё нет.
     */
    data class Known(val quantity: Quantity, val confirmed: Boolean = true) : EffectiveAmount

    /**
     * Исход операции не установлен: включён ли наш расход в серверный остаток, неизвестно.
     *
     * Повторять расход нельзя — списали бы дважды, — и выдумывать число тоже: до сверки
     * показывается последнее наблюдение и требование проверки (PLAN E3).
     */
    data class NeedsRecount(
        val lastObserved: Quantity,
        val unresolvedOperationIds: List<Uuid>
    ) : EffectiveAmount {
        init {
            require(unresolvedOperationIds.isNotEmpty()) {
                "сверка требуется из-за названных операций, а не сама по себе"
            }
        }
    }

    /** Число, если оно у нас есть. `null` — до сверки точного количества не обещаем. */
    val quantityOrNull: Quantity?
        get() = (this as? Known)?.quantity
}
