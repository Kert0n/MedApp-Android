package com.kert0n.medapp.domain.model.course

/**
 * Состояние курса.
 *
 * [DRAFT] — не полуфабрикат, а законное сохраняемое состояние: «записал у врача, куплю завтра».
 * У черновика может не быть ни расписания, ни дозы, ни источников, и он всё равно курс (PLAN D5).
 *
 * [COMPLETED] и [CANCELLED] историю не переписывают: состоявшиеся приёмы остаются как были.
 */
enum class CourseStatus {
    DRAFT,        // ещё нет расписания или источников
    ACTIVE,
    COMPLETED,    // календарь закончился, неотвеченных пунктов нет
    CANCELLED
}
