package com.kert0n.medapp.domain.model.sync

/**
 * Смысл действия, которое ещё не уехало на сервер: «списать столько», «завести пачку», «снять
 * бронь».
 *
 * **Величина:** другое количество — другое намерение, а не изменённое. Уже подготовленный запрос
 * неизменен (PLAN E2, E3), поэтому «поправить намерение на месте» — не то, что здесь бывает.
 *
 * **Вид намерения — это тип**, как и вид движения остатка (PLAN D7): смысл полей задаёт вид,
 * поэтому у расхода есть количество и приём, у переноса — целевая аптечка, а проверок сочетаний
 * нет вовсе. Каждый вид лежит в своём файле этого пакета: их двенадцать, и списком каталога они
 * видны, а не поиском внутри одного объявления.
 *
 * **Доменный тип без сети.** Намерение говорит, что человек хотел сделать; каким методом, по
 * какому пути и с каким предусловием это уедет, знает `PreparedRequest` слоя данных, и в
 * доменные вычислители он не попадает. Проекция незакрытых намерений на подтверждённый остаток
 * (PLAN E1) считается по этим значениям, а не по строкам запросов.
 *
 * Суффикс, а не префикс: у намерения первым читается глагол — `ConsumeIntent`, `SetClaimIntent`.
 * Порядок применения задаёт `sequence` записи очереди, и его здесь нет: номер принадлежит базе,
 * которая его выдаёт, а домен получает намерения уже в порядке.
 */
sealed interface SyncIntent
