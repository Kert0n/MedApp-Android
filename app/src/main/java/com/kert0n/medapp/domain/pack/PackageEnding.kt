package com.kert0n.medapp.domain.pack

import com.kert0n.medapp.domain.stock.StockMovement

/**
 * Конец жизни коробки — событие, а не отсутствие строки. У него есть то, что остаётся навсегда
 * ([record]), и то, чем он объясняется в истории ([trace]).
 *
 * След выбирает переход, который построил конец, а не тот, кто его записывает: расход объясняет
 * себя сам — приём и есть учётная запись о нём, — а выброшенная коробка объясняется утилизацией,
 * иначе «истрачено за период» не сходится и остаток пропадает без объяснения (PLAN D7, H6).
 * Собрать конец мимо переходов [Package] нечем, поэтому «выбросил, а следа нет» не выражается.
 *
 * Значение целиком: хранение получает его одной дверью и одной транзакцией пишет след, снимает
 * источник у курса и убирает строку — порознь этого не бывает (PLAN D3, F5).
 */
class PackageEnding internal constructor(
    val pkg: Package,
    val trace: StockMovement?
) {

    /** Вечная запись о коробке: за неё держатся приёмы и движения, и конец она переживает (D3, D6). */
    val record: PackageRecord get() = pkg.record

    override fun toString(): String =
        "PackageEnding(pkg=${pkg.id}, trace=${trace?.let { it::class.simpleName } ?: "нет"})"
}
