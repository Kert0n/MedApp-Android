package com.kert0n.medapp.domain.intake

import kotlin.uuid.Uuid

/**
 * Приём: пункт курса вместе с ответом на него — либо внеплановый факт.
 *
 * **Это два понятия, а не одно с одиннадцатью необязательными полями.** Пункт курса порождён
 * редакцией расписания и знает своё назначенное время; внеплановый приём — просто состоявшийся
 * факт, и планировать его нечем. Пока они были одним классом, их различали восемь `require` над
 * сочетаниями `null`; комбинацию, которую забыли запретить, нельзя было отличить от законной.
 * Тот же довод, что развёл семь видов движения остатка по типам (PLAN D7).
 *
 * **Сущность, а не величина.** Подтверждение не делает приём другим приёмом: это тот же пункт, у
 * которого появился ответ. Тождество — [id], равенство по нему, состояние меняют только переходы.
 *
 * **Учёта расхода здесь нет.** Состояние учёта, связь с операцией очереди и с ручной сверкой
 * живут в `IntakeSyncState` слоя данных: в локальной аптечке исходящих операций не существует
 * вовсе (PLAN E1), значит понятие есть только из-за сервера. Инвариант «у подтверждённого приёма
 * расход не бывает неприменим» — правило транзакции, где PLAN его и держит (F5).
 */
sealed interface Intake {

    val id: Uuid

    /** Единица НА МОМЕНТ СОБЫТИЯ: смена единицы прошлые отчёты не переписывает. */
    val unitId: Uuid

    /** Производное от ответа: отдельного поля, способного с ним разойтись, нет. */
    val status: IntakeStatus

    /** Что фактически принято. `null` — приёма не было (PLAN D6). */
    val taken: TakenDose?
}
