package com.kert0n.medapp.domain.model.pack

import java.time.LocalDate
import java.time.YearMonth

/**
 * Срок годности: **последний день, когда пачка ещё годна**.
 *
 * Величина, а не голая `LocalDate`: «до 31 марта» и «31 марта» — разные утверждения, и путать их
 * дорого. Имя поля [lastDay] говорит, какое из них здесь записано, поэтому вопрос «включительная
 * дата или нет» не встаёт ни у одного вызывающего — на него уже ответил тип.
 *
 * Правила спрашивают у самого значения, а не у набора функций над датой: [PackageFacts] отвечает
 * про свою пачку, `PackageAvailability` — про пачку, которой у него на руках нет (PLAN D4), и оба
 * зовут одни и те же [isExpiredOn] и [expiresWithin]. Двух знаков сравнения в двух местах,
 * которые разойдутся при первом рефакторинге, просто нет.
 *
 * `null` вместо `ExpiryDate` означает «срока не знаем». Отсутствующий срок не выдумывается: про
 * пачку без даты мы не знаем ничего, и «просрочена» — не то, что говорят о неизвестном (PLAN D8).
 */
data class ExpiryDate(val lastDay: LocalDate) {

    /** Дата **включительная**: пачка, годная «до 31 марта», просрочена только 1 апреля. */
    fun isExpiredOn(date: LocalDate): Boolean = lastDay.isBefore(date)

    /**
     * Истекает ли срок не позже чем через [days] дней, считая [date] включительно.
     *
     * Именно окно, а не «ровно за N дней»: пороги 3 и 1 день (PLAN D8) проверяет фоновая задача,
     * а она может задержаться и перепрыгнуть точную дату. Уже просроченная пачка «скоро» не
     * истекает — у неё другое состояние и другое сообщение.
     */
    fun expiresWithin(date: LocalDate, days: Long): Boolean {
        require(days >= 0) { "окно предупреждения не бывает отрицательным" }
        if (isExpiredOn(date)) return false
        return !lastDay.isAfter(date.plusDays(days))
    }

    companion object {

        /**
         * Названный месяц годен целиком, и годность кончается его последним днём.
         *
         * На упаковках печатают «03.2027», и это **не** первое марта: считать иначе значило бы
         * отнять почти месяц годности. Правило продуктовое, поэтому живёт в домене, а
         * распознавание самой записи — в адаптере ввода (PLAN D3).
         */
        fun of(month: YearMonth): ExpiryDate = ExpiryDate(month.atEndOfMonth())
    }
}
