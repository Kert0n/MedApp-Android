package com.kert0n.medapp.domain.model.pack

import java.time.LocalDate
import java.time.YearMonth

/**
 * Продуктовые правила о сроке годности, не зависящие ни от того, как его ввели, ни от того, кто
 * спрашивает.
 *
 * **Спрашивают его двое.** Пачка отвечает про себя ([PackageFacts.isExpiredOn]), а проекция
 * доступного — про пачку, которой у неё на руках нет: она несёт только дату (PLAN D4). Пока
 * сравнение жило у пачки, второму спрашивающему пришлось бы повторить `isBefore` у себя — а это
 * ровно тот знак, который «поправят» при рефакторинге первым. Поэтому правило здесь одно, а
 * [PackageFacts] ему делегирует.
 */
object ExpiryDate {

    /**
     * Названный месяц годен целиком, и годность кончается его последним днём.
     *
     * На упаковках печатают «03.2027», и это **не** первое марта: считать иначе значило бы отнять
     * почти месяц годности. Правило продуктовое, поэтому живёт в домене, а распознавание самой
     * записи — в адаптере ввода (PLAN D3).
     */
    fun lastDayOf(month: YearMonth): LocalDate = month.atEndOfMonth()

    /**
     * Дата **включительная**: пачка, годная «до 31 марта», просрочена только 1 апреля.
     *
     * Отсутствующий срок не выдумывается: про пачку без даты мы не знаем ничего, и «просрочена» —
     * не то, что говорят о неизвестном (PLAN D8).
     */
    fun isExpired(expiresOn: LocalDate?, on: LocalDate): Boolean = expiresOn?.isBefore(on) == true

    /**
     * Истекает ли срок не позже чем через [days] дней, считая [on] включительно.
     *
     * Именно окно, а не «ровно за N дней»: пороги 3 и 1 день (PLAN D8) проверяет фоновая задача,
     * а она может задержаться и перепрыгнуть точную дату. Уже просроченная пачка «скоро» не
     * истекает — у неё другое состояние и другое сообщение.
     */
    fun expiresWithin(expiresOn: LocalDate?, on: LocalDate, days: Long): Boolean {
        require(days >= 0) { "окно предупреждения не бывает отрицательным" }
        val expires = expiresOn ?: return false
        if (expires.isBefore(on)) return false
        return !expires.isAfter(on.plusDays(days))
    }
}
