package com.kert0n.medapp.domain.model.intake

/**
 * Состояние приёма. План и факт — одна запись: запланированный приём это приём, который ещё не
 * состоялся (PLAN D6).
 *
 * Переходы: [PLANNED] → [TAKEN] / [SKIPPED] / [MISSED] / [CANCELLED], и [MISSED] → [TAKEN] после
 * повторной проверки источника и остатка. [SKIPPED] не подтверждается неявно: отмена пропуска —
 * отдельное явно заданное действие, и в первой версии она не обещается.
 */
enum class IntakeStatus {

    /** Пункт плана, ответа ещё нет. */
    PLANNED,

    /** Подтверждён: есть фактическое количество, пачка и момент. */
    TAKEN,

    /** Человек отказался. Расхода нет, потребность уменьшается. */
    SKIPPED,

    /** Не ответил до конца календарного дня курса в его зоне (PLAN C1). */
    MISSED,

    /** Плановый пункт отменён вместе с курсом. История остаётся. */
    CANCELLED
}
