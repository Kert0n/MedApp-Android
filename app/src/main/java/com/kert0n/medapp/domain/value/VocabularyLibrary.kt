package com.kert0n.medapp.domain.value

import com.kert0n.medapp.domain.Unavailability

/**
 * Словарь единиц и форм: чем считают количества. Словарь принадлежит серверу и только растёт,
 * поэтому здесь два вопроса — что известно сейчас и чем пополнить.
 *
 * Пополнение нужно, лишь когда не известно ничего: без единицы не показать ни одного количества,
 * а **свежесть** словаря условием работы не является — настроенное приложение открывается без
 * связи (PLAN J3).
 */
interface VocabularyLibrary {

    suspend fun known(): Vocabulary

    /** Пополняет словарь с сервера; `null` — пополнили, иначе названо, почему не вышло. */
    suspend fun refresh(): Unavailability?
}
