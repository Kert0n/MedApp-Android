package com.kert0n.medapp.domain.intake

import com.kert0n.medapp.domain.pack.PackageRef
import com.kert0n.medapp.domain.value.Dose
import java.time.Instant

/**
 * Состоявшийся приём: сколько, откуда и когда.
 *
 * Обстоятельства события — [amount] с единицей, в которой считали тогда, и [at], который называет
 * человек, — записаны в факте и не перечитываются. [pkg] — ссылка на сегодняшнее: имя, аптечка и
 * нынешняя единица пачки читаются по ней и потому текущие (PLAN D6). Факт против сегодняшней
 * пачки не проверяется: он был допустим в момент записи, а проверяет это акт — [Package.take].
 * Пачка может отличаться от плановой, и расход относится к фактической (D5).
 *
 * `null` — **пачки больше нет**: её удалили, а приём был. Факт лечения держится на записи эпизода
 * и на себе самом, а не на картонной коробке, которой человек давно лишился (PLAN D5, D6). В
 * момент записи пачка есть всегда: её приносит [Package.take].
 */
data class TakenDose(
    val pkg: PackageRef?,
    val amount: Dose,
    val at: Instant
)
