package com.kert0n.medapp.domain.intake

import com.kert0n.medapp.domain.pack.Package
import com.kert0n.medapp.domain.value.Dose
import java.time.Instant

/**
 * Состоявшийся приём: сколько, из какой пачки и когда — три поля, которые бывают только вместе.
 * Пачка может отличаться от плановой, и расход относится к фактической (PLAN D5). Аптечка у
 * пачки: «принял из пачки, лежащей в другой аптечке» здесь невыразимо, а не проверяется. Единица
 * записана на момент события: смена единицы прошлые отчёты не переписывает (D6).
 */
data class TakenDose(
    val pkg: Package,
    val amount: Dose,
    val at: Instant
) {
    init {
        // Пачку передают целиком как раз затем, чтобы проверить это отношение: две таблетки из
        // флакона, который меряют миллилитрами, — не факт, а испорченная история.
        require(amount.unit == pkg.quantity.unit) {
            "принятое измеряется единицей той пачки, из которой взято"
        }
    }
}
