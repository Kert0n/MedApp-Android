package com.kert0n.medapp.storage.database

/**
 * Список в запрос `IN (...)` идёт порциями. Длину такого списка задают данные — пачки аптечки,
 * лишние плановые пункты курса, — а SQLite принимает ограниченное число переменных на запрос и
 * на более длинном бросает. Порция — свойство базы, а не вызывающего, поэтому предел один и
 * лежит здесь.
 *
 * Порядок внутри порции сохраняется, порядок порций — порядок исходного списка; складывает
 * ответы вызывающий, потому что складываются они по-разному: чтения — списком, записи — счётом.
 */
internal fun <T> Iterable<T>.chunkedForQuery(): List<List<T>> = chunked(SQLITE_VARIABLE_LIMIT)

/** Предел переменных в одном запросе SQLite: с запасом от 999, которые обещает движок. */
private const val SQLITE_VARIABLE_LIMIT = 500
