package com.kert0n.medapp.storage.pack

/**
 * Что из снимка легло. Половины две, и запоздать может любая: [pack] — серверная часть пачки,
 * [claims] — картина броней и её версия. Запоздалая половина не откатывает свежую, и своей
 * половины другая не касается (PLAN B3, E1).
 *
 * Снимок без прочитанной картины броней её не кладёт: пустая версия значит «не читалась».
 */
data class SnapshotApplied(val pack: Boolean, val claims: Boolean)
