package com.kert0n.medapp.presentation

/**
 * Почему не вышло — значением, а не текстом: текст для человека живёт в `R.string.*`, и слои
 * данных о нём не знают (AGENTS).
 *
 * Случаи различаются тем, что человеку делать дальше. Коды ответов и причины отказа сети сюда не
 * доезжают: их раскладывает сценарий, потому что «404 у пачки» и «404 у аптечки» ведут человека
 * к разному, а экрану нужно одно — что показать и есть ли смысл в повторе.
 */
enum class LoadFailure {

    /** Связи нет: повтор осмыслен, как только она появится. */
    NO_CONNECTION,

    /** Сервер не ответил или ответил не по контракту: повтор осмыслен позже. */
    SERVER_UNAVAILABLE,

    /** Сервер нас не принял: повтор тем же не поможет, нужно решение человека. */
    NOT_AUTHORIZED,

    /**
     * Устройство не смогло записать то, без чего дальше нельзя. Повтор осмыслен: место могло
     * освободиться, — но причина не серверная, и человеку сказать надо другое (PLAN G2).
     */
    DEVICE_STORAGE
}
