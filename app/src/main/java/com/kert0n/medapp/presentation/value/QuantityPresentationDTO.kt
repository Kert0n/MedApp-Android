package com.kert0n.medapp.presentation.value

/**
 * Величины в том виде, в каком их держит экран: строками, как человек напечатал.
 *
 * Это третье направление DTO — представление, рядом с сетевым и хранением. Форма ввода не может
 * держать `Quantity`: пока человек печатает, там лежит «12,», «0.0000001» или пусто, и ни одно
 * из этих состояний величиной не является. Приводит их к домену маппер представления — так же,
 * как сетевой маппер приводит домен к телу запроса.
 *
 * Единица — [UnitPresentationDTO], а не объект словаря: форма держит то, что человек выбрал из
 * списка, вместе с его именем, и переименование единицы экран замечает.
 */
data class QuantityPresentationDTO(val amount: String, val unit: UnitPresentationDTO)
