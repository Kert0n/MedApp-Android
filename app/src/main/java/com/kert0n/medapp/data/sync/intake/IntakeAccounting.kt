package com.kert0n.medapp.data.sync.intake

/**
 * Где находится расход, записанный приёмом: в локальном остатке, в очереди, на сервере — или
 * неизвестно где.
 *
 * Слой данных, а не домен. В локальной аптечке исходящих операций нет вовсе (PLAN E1), и всё это
 * различение существует только из-за сервера: ни одно бизнес-правило о приёме — переходы, доза,
 * обеспечение — его не читает.
 */
enum class IntakeAccounting {

    /** Расхода нет: плановый, пропущенный, неотвеченный или отменённый пункт. */
    NOT_APPLICABLE,

    /** Локальный остаток и факт записаны одной транзакцией (PLAN F5). */
    LOCAL_APPLIED,

    /** Факт есть, серверная команда ещё не подтверждена. */
    PENDING,

    /** Подтверждено ответом или строгим свидетельством (PLAN E3). */
    REMOTE_APPLIED,

    /** Неизвестно, включён ли факт в серверный остаток. Повторно расход не отправляется. */
    NEEDS_RECOUNT,

    /** Вошёл в подтверждённую ручную сверку; исход старого запроса не выдумывается. */
    RECONCILED
}
