/*
 * Провод: типы ровно той формы, в какой их отдаёт и принимает сервер.
 *
 * Здесь ничего не «удобнее» — удобство начинается уровнем выше, в доменных моделях. Классы
 * повторяют [контракт](https://github.com/Kert0n/MedApp-Server/blob/main/open-api.yaml) поле в
 * поле, включая обязательность и имена. Компилятор этого соответствия не проверяет, и
 * расхождение находится по-разному в две стороны: в запросе — 400 от сервера, в ответе —
 * `SerializationException` при разборе, уже на телефоне.
 *
 * Идентификаторы и величины — строки, потому что на проводе они и есть строки. Величину сервер
 * отдаёт строкой намеренно: в `numeric(19, 6)` помещается девятнадцать значащих цифр, а `Double`
 * держит семнадцать — по диапазону такое число проходит, а по точности нет, и разбор числом
 * молча округлял бы половину таблетки. В `BigDecimal` и `UUID` они превращаются на границе с
 * доменом — это работа отображения, а не провода.
