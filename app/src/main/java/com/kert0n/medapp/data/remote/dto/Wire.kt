package com.kert0n.medapp.data.remote.dto

/*
 * Провод: типы ровно той формы, в какой их отдаёт и принимает сервер.
 *
 * Здесь ничего не «удобнее» — удобство начинается уровнем выше, в доменных моделях. Эти классы
 * повторяют [контракт](https://github.com/Kert0n/MedApp-Server/blob/main/open-api.yaml) поле в
 * поле, включая обязательность и имена: расхождение здесь — это 400 от сервера, а не ошибка
 * компиляции.
 *
 * ## Почему идентификаторы и величины — строки
 *
 * На проводе они и есть строки. Идентификатор сервер сериализует как UUID-строку, а величину —
 * намеренно строкой, а не числом: предел `numeric(19, 6)` не помещается в `Double`, и разбор
 * числом молча округлял бы половину таблетки. Переводить строку в `BigDecimal` и `UUID` — работа
 * отображения в домен, а не провода.
 *
 * ## Почему у необязательных полей стоит `= null`
 *
 * `Json` по умолчанию не пишет значения по умолчанию, поэтому неуказанное поле запроса просто не
 * поедет. Для `PATCH` это и есть нужная семантика: `null` значит «не трогать», а не «очистить» —
 * так же читает его и сервер.
 *
 * ## Версии
 *
 * Команда предъявляет версию того, что видела. Не прислать её — 428, прислать несовпавшую — 412,
 * а в синхронизации, где версий две, несовпадение даёт 409. Поэтому `version` необязателен в
 * типах, но обязателен по смыслу: клиент, забывший его, узнает об этом от сервера.
 */
