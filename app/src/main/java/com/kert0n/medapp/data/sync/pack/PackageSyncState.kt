package com.kert0n.medapp.data.sync.pack

import java.time.Instant
import kotlin.uuid.Uuid

/**
 * Обвязка синхронизации упаковки: то, что нужно хранению и сети, и не нужно правилам.
 *
 * Версия — токен предусловия, который клиент **не толкует**, а возвращает серверу вместе с
 * командой (PLAN B3). О значении, которое запрещено толковать, нельзя сформулировать
 * бизнес-правило, поэтому в домене ему места нет: ни один вычислитель D4–D5 его не читает, а
 * перевод сервера на другой механизм предусловия не должен трогать модель.
 *
 * Версий две и они независимы: состояние пачки и картину броней двигают разные команды и разные
 * люди. Поэтому одним `ETag` их не выразить, и здесь они лежат порознь.
 *
 * [syncedAt] — когда мы последний раз сверялись; это нужно экрану состояния синхронизации
 * (PLAN H3 №28), а не расчётам.
 */
data class PackageSyncState(
    val packageId: Uuid,
    val version: Long? = null,        // null — на сервере пачка ещё не создана
    val claimsVersion: Long? = null,  // null — картина броней не читалась
    val syncedAt: Instant? = null
) {
    init {
        require(version == null || version >= 0) { "версия пачки не бывает отрицательной" }
        require(claimsVersion == null || claimsVersion >= 0) {
            "версия картины броней не бывает отрицательной"
        }
    }

    /** Существует ли пачка на сервере — единственный осмысленный вопрос к версии вне сети. */
    val isOnServer: Boolean get() = version != null
}
